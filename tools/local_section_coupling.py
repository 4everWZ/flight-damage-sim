#!/usr/bin/env python3
"""One falsifiable localized section-loss experiment, isolated from production.

Compare frozen local circulation scaling with a self-consistent wake solve.
Only the new explicit sectional fixture is used. A Gaussian slope perturbation
is a declared synthetic constitutive intervention, not perforation or legacy
damage interpretation. Force/power checks are steady aerodynamic identities.
"""
import csv
import json
import math
from lifting_line_reference import ROOT, RESULTS, V, RHO, Q, solve, local, integrate


def projected_frozen(intact, span, fraction, modes, quadrature=1024):
    # Fourier projection reconstructs the wake generated by the locally scaled
    # circulation. It does NOT solve the damaged section closure.
    h = math.pi/quadrature
    values = [(i*h, local(intact, span, i*h)[0]*fraction(i*h)
               * (4 if i % 2 else 2)) for i in range(1, quadrature)]
    return [h/3/(math.pi*span*V)*sum(gamma*math.sin(n*t) for t, gamma in values)
            for n in range(1, modes+1)]


def metrics(coefficients, span, chord, alpha, slope, section):
    angle_at = alpha if callable(alpha) else lambda t: alpha
    area, ar = span*chord, span/chord
    lift = Q*area*math.pi*ar*coefficients[0]
    induced = Q*area*math.pi*ar*sum(n*a*a for n, a in enumerate(coefficients, 1))
    roll = -math.pi*RHO*V*V*span**3/8*coefficients[1]
    def density(t):
        gamma, ai = local(coefficients, span, t)
        cl = 2*gamma/(V*chord)
        return RHO*V*gamma, ai, cl, span/2*math.sin(t)
    lift_i = integrate(lambda t: density(t)[0]*density(t)[3])
    induced_i = integrate(lambda t: density(t)[0]*density(t)[1]*density(t)[3])
    roll_i = integrate(lambda t: -span/2*math.cos(t)*density(t)[0]*density(t)[3])
    profile = integrate(lambda t: Q*chord*(section['profile_cd0']
                                         + section['profile_cd_cl_squared']*density(t)[2]**2)
                        * density(t)[3])
    residual, interior, max_angle = [], [], 0.
    for i in range(1, 512):
        t = math.pi*(i+.31)/513
        y = span/2*math.cos(t)
        gamma, ai = local(coefficients, span, t)
        error = abs(2*gamma/(V*chord) - slope(t)*(angle_at(t)-ai))
        residual.append(error)
        if abs(y) <= .9*span/2:
            interior.append(error)
        max_angle = max(max_angle, abs(angle_at(t)-ai))
    assert max_angle < math.radians(section['valid_alpha_deg'][1])
    assert abs(lift_i/lift-1) < 1e-10
    assert abs(induced_i/induced-1) < 1e-10
    assert abs(roll_i-roll) < 1e-7
    assert induced > 0 and profile > 0
    return {'lift_N': lift, 'roll_Nm': roll, 'induced_drag_N': induced,
            'profile_drag_N': profile, 'induced_power_W': induced*V,
            'max_section_cl_closure_residual': max(residual),
            'interior_section_cl_closure_residual': max(interior),
            'max_effective_angle_deg': math.degrees(max_angle),
            'lift_integral_relative_error': abs(lift_i/lift-1),
            'induced_power_integral_relative_error': abs(induced_i/induced-1)}


def main():
    fixture = json.loads((ROOT/'data/section-wing-reference.json').read_text())
    geometry, section = fixture['geometry'], fixture['section_2d']
    span, chord = geometry['span_m'], geometry['chord_m']
    alpha = math.radians(2-section['zero_lift_alpha_deg'])
    a0, center, width, loss = section['cl_alpha_per_rad'], -3., .6, .5
    def fraction(t, patch_center=center):
        y = span/2*math.cos(t)
        return 1-loss*math.exp(-((y-patch_center)/width)**2)
    slope = lambda t: a0*fraction(t)
    records, coefficients = {}, {}
    for modes in (32, 64, 96, 128):
        intact = solve(span, lambda t: chord, lambda t: alpha, a0, modes)
        coupled = solve(span, lambda t: chord, lambda t: alpha, slope, modes)
        frozen = projected_frozen(intact, span, fraction, modes)
        records[modes] = {
            'intact': metrics(intact, span, chord, alpha, lambda t: a0, section),
            'frozen_local_scaling': metrics(frozen, span, chord, alpha, slope, section),
            'recoupled': metrics(coupled, span, chord, alpha, slope, section)}
        coefficients[modes] = {'intact': intact, 'frozen_local_scaling': frozen,
                               'recoupled': coupled}
    # Endpoint check: a constant callable slope must retain the existing solve.
    constant = solve(span, lambda t: chord, lambda t: alpha, lambda t: a0, 128)
    assert constant == coefficients[128]['intact']
    mirrored = solve(span, lambda t: chord, lambda t: alpha,
                     lambda t: a0*fraction(t, -center), 128)
    mirrored_metrics = metrics(mirrored, span, chord, alpha,
                               lambda t: a0*fraction(t, -center), section)
    fine = records[128]
    assert abs(mirrored_metrics['lift_N']-fine['recoupled']['lift_N']) < 1e-8
    assert abs(mirrored_metrics['roll_Nm']+fine['recoupled']['roll_Nm']) < 1e-8
    convergence = {k: abs(records[96]['recoupled'][k]-fine['recoupled'][k])
                   / max(abs(fine['recoupled'][k]), 1.)
                   for k in ('lift_N', 'roll_Nm', 'induced_drag_N')}
    assert max(convergence.values()) < 1e-5
    # The frozen intervention must demonstrably violate the self-generated
    # wake's local section relation; do not call it a physical alternative.
    assert fine['frozen_local_scaling']['interior_section_cl_closure_residual'] > .01
    assert fine['recoupled']['interior_section_cl_closure_residual'] < 1e-4
    samples, right_differences, frozen_right_differences = [], [], []
    for y in (-4., -3., -2., 0., .5, 1., 2., 3., 4.):
        t = math.acos(2*y/span)
        row = {'y_m': y, 'section_slope_fraction': fraction(t)}
        for name, a in coefficients[128].items():
            gamma, ai = local(a, span, t)
            row[name+'_load_N_m'] = RHO*V*gamma
            row[name+'_downwash_m_s'] = V*ai
        samples.append(row)
        if y >= .5:
            right_differences.append(row['recoupled_load_N_m']-row['intact_load_N_m'])
            frozen_right_differences.append(row['frozen_local_scaling_load_N_m']-row['intact_load_N_m'])
    assert max(abs(x) for x in right_differences) > 1.
    assert max(abs(x) for x in frozen_right_differences) < .001
    same_lift_scale = fine['intact']['lift_N']/fine['recoupled']['lift_N']
    same_lift = {'alpha_deg': 2*same_lift_scale,
                 'recoupled_induced_drag_N': fine['recoupled']['induced_drag_N']*same_lift_scale**2,
                 'intact_induced_drag_N': fine['intact']['induced_drag_N'],
                 'meaning': 'Linear same-total-lift rescaling, not a trimmed-flight or control-authority result.'}
    assert fine['recoupled']['max_effective_angle_deg']*same_lift_scale < section['valid_alpha_deg'][1]
    RESULTS.mkdir(exist_ok=True)
    summary = {'intervention': {'alpha_deg': 2., 'center_y_m': center,
                               'width_m': width, 'peak_section_slope_loss_fraction': loss,
                               'slope_fraction': '1-loss*exp(-((y-center)/width)^2)',
                               'meaning': 'Synthetic smooth sectional slope reduction only, with geometry, zero-lift angle and declared profile law unchanged. No mapping to perforation, lost area, old lift_efficiency, structure or actual aircraft.'},
               'cases_by_modes': records, 'mirrored_recoupled': mirrored_metrics,
               'relative_refinement_96_to_128': convergence,
               'same_total_lift_comparison': same_lift,
               'station_samples': samples,
               'mechanism': 'Frozen circulation scaling leaves far-wing load unchanged but violates the section relation when its own wake is reconstructed. The recoupled solution satisfies that relation and changes load on the effectively intact far wing. Steady induced power/force/moment identities are checked; no time-integrated 6DoF energy or local structural-stress claim.'}
    (RESULTS/'local-section-summary.json').write_text(json.dumps(summary, indent=2)+'\n')
    with (RESULTS/'local-section-loads.csv').open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(samples[0]))
        writer.writeheader()
        writer.writerows(samples)
    print(json.dumps({'fine': fine, 'relative_refinement_96_to_128': convergence,
                      'station_samples': samples}, indent=2))


if __name__ == '__main__':
    main()
